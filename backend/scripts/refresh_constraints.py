"""Regenerate backend/constraints.txt: the exact version of every package (direct and
transitive) that requirements.txt resolves to today.

requirements.txt says what the app is compatible with, as ranges. constraints.txt says
what we actually run and test, as exact pins, so a build next month installs the same
thing as a build today. Without it, `sqlalchemy>=2.0,<3.0` quietly became 2.1 and
changed which database driver a bare postgresql:// URL meant, crashing a fresh install.

    cd backend
    python scripts/refresh_constraints.py     # then run the tests, review the diff, commit

Install with:  pip install -r requirements.txt -c constraints.txt

Resolves in a throwaway virtualenv, ignoring the current pins (that is the point of a
refresh). Platform-specific packages this OS cannot see are added from constraints-extras.txt. Use the same Python minor version as production (render.yaml sets
PYTHON_VERSION); a different one can resolve to different versions.
"""
import datetime
import os
import subprocess
import sys
import tempfile
import venv

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = ("pip==", "setuptools==", "wheel==")


def run(args, **kwargs):
    return subprocess.run(args, check=True, capture_output=True, text=True, encoding="utf-8", **kwargs)


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        env_dir = os.path.join(tmp, "venv")
        venv.EnvBuilder(with_pip=True).create(env_dir)
        bin_dir = os.path.join(env_dir, "Scripts" if os.name == "nt" else "bin")
        python = os.path.join(bin_dir, "python.exe" if os.name == "nt" else "python")

        print("Resolving requirements.txt in a clean environment...", flush=True)
        run([python, "-m", "pip", "install", "--disable-pip-version-check", "-q",
             "-r", os.path.join(BACKEND, "requirements.txt")])
        frozen = run([python, "-m", "pip", "freeze", "--disable-pip-version-check"]).stdout.splitlines()

    pins = sorted(
        (line.strip() for line in frozen if line.strip() and not line.startswith(SKIP) and " @ " not in line),
        key=str.lower,
    )
    header = [
        f"# Generated by scripts/refresh_constraints.py on {datetime.date.today().isoformat()} "
        f"with Python {sys.version_info.major}.{sys.version_info.minor}. Do not edit by hand.",
        "# Exact versions of every package requirements.txt resolves to, so builds are reproducible.",
        "# Install with:  pip install -r requirements.txt -c constraints.txt",
        "# A pin for a package that is not needed on your platform (e.g. colorama on Linux) is ignored.",
        "",
    ]
    # Packages pip only installs on some platforms (uvloop), which this OS cannot see.
    extras_path = os.path.join(BACKEND, "constraints-extras.txt")
    extras = []
    if os.path.exists(extras_path):
        extras = [line.strip() for line in open(extras_path, encoding="utf-8") if line.strip() and not line.startswith("#")]
    pins = pins + extras

    out_path = os.path.join(BACKEND, "constraints.txt")
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(header + pins) + "\n")
    print(f"Wrote {len(pins)} pins to {out_path}")


if __name__ == "__main__":
    main()
